export interface RenderBox {
  slope?: boolean;
  along: number;
  across: number;
  z: number;
  len: number;
  wid: number;
  h: number;
  top: number;
  left: number;
  right: number;
}

export interface DebrisRecipe {
  remnants: number;
  fragments: number;
  particles: number;
  remnantScale: number;
  pileMass: number;
  shape: DebrisShape;
}

export interface AssetDef {
  id: string;
  family: AssetFamily;
  tags: readonly AssetTag[];
  footprint: { w: number; d: number; h: number };
  collision: { w: number; d: number };
  material: Material;
  hp: number;
  mass: number;
  resistance: number;
  bladeMul: number;
  trackHazard: number;
  cash: number;
  destruction: DestructionProfile;
  debris: DebrisRecipe;
  variants: number;
  boxes: readonly RenderBox[];
  zones: readonly LotCompat[];
  roadsideOk: boolean;
  minClear: number;
  sparks: boolean;
  birdGag: boolean;
  explodeRadius: number;
  explodeImpulse: number;
  explodeDamage: number;
  yawResist: number;
  /** Scrap value class: destroying the asset pays its cash as a labelled copper or mechanical salvage popup. */
  salvage?: SalvageKind;
  /** Burst and sound when the asset breaks: venting refrigerant, exhaust soot, or an electrical arc. */
  breakFx?: MachineFx;
  /** Fixed scenery such as a house-sized boulder: hits never wear it down, so it stays a solid obstacle. */
  immovable?: boolean;
  campaign?: CampaignPlacement;
}

const emptyPose = (): PropPose => ({ lean: 0, leanX: 0, leanY: 0, crush: 0, roll: 0 });

function box(
  along: number,
  across: number,
  z: number,
  len: number,
  wid: number,
  h: number,
  top: number,
  left: number,
  right: number,
): RenderBox {
  return { along, across, z, len, wid, h, top, left, right };
}

function debris(
  remnants: number,
  fragments: number,
  particles: number,
  remnantScale: number,
  pileMass: number,
  shape: DebrisShape,
): DebrisRecipe {
  return { remnants, fragments, particles, remnantScale, pileMass, shape };
}

