const BY_ID = new Map(ASSET_CATALOG.map((a) => [a.id, a]));

export const NEW_ASSET_IDS = ASSET_CATALOG.filter((a) => a.family !== "legacy").map((a) => a.id);

export function getAsset(id: string): AssetDef {
  const found = BY_ID.get(id);
  if (!found) throw new Error(`Unknown asset ${id}`);
  return found;
}

export function tryAsset(id: string): AssetDef | undefined {
  return BY_ID.get(id);
}

export function assetsByFamily(family: AssetFamily): AssetDef[] {
  return ASSET_CATALOG.filter((a) => a.family === family);
}

export interface CatalogIssue {
  code: string;
  detail: string;
}

export function validateCatalog(defs: readonly AssetDef[] = ASSET_CATALOG): { ok: boolean; issues: CatalogIssue[] } {
  const issues: CatalogIssue[] = [];
  const seen = new Set<string>();
  for (const d of defs) {
    if (seen.has(d.id)) issues.push({ code: "dup", detail: `duplicate id ${d.id}` });
    seen.add(d.id);
    if (!d.id.trim()) issues.push({ code: "id", detail: "empty asset id" });
    if (d.footprint.w <= 0 || d.footprint.d <= 0 || d.footprint.h <= 0) {
      issues.push({ code: "footprint", detail: `${d.id} has a non-positive footprint` });
    }
    if (d.hp <= 0 || d.mass <= 0) issues.push({ code: "stats", detail: `${d.id} needs positive hp and mass` });
    if (d.variants < 1) issues.push({ code: "variant", detail: `${d.id} needs at least one variant` });
    if (d.zones.length === 0) issues.push({ code: "zone", detail: `${d.id} has no compatible zones` });
    if (d.cash < 0) issues.push({ code: "cash", detail: `${d.id} cash is negative` });
    if (d.destruction === "explosive" && d.explodeRadius <= 0) {
      issues.push({ code: "explode", detail: `${d.id} explosive profile missing radius` });
    }
  }
  return { ok: issues.length === 0, issues };
}

let propSeq = 1;

export function resetPropIds(): void {
  propSeq = 1;
}

export function spawnAsset(
  assetId: string,
  x: number,
  y: number,
  heading = 0,
  variant = 0,
  size?: { w: number; d: number },
): Prop {
  const def = getAsset(assetId);
  const w = size?.w ?? def.footprint.w;
  const d = size?.d ?? def.footprint.d;
  return {
    id: propSeq++,
    assetId: def.id,
    kind: def.id,
    variant: ((variant % def.variants) + def.variants) % def.variants,
    x,
    y,
    w,
    d,
    hp: def.hp,
    maxHp: def.hp,
    heading,
    elev: 0,
    broken: false,
    material: def.material,
    pose: emptyPose(),
    vx: 0,
    vy: 0,
    omega: 0,
  };
}

export function propDef(prop: Prop): AssetDef {
  return getAsset(prop.assetId);
}
